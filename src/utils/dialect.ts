/**
 * Translates standard child guidance Arabic text into Sudanese colloquial children's Arabic.
 */
export function translateToSudanese(text: string): string {
  if (!text) return text;

  // Try exact sentence first to preserve high-fidelity translation
  const cleanKey = text.trim();
  if (SUDANESE_TRANSLATIONS[cleanKey]) {
    return SUDANESE_TRANSLATIONS[cleanKey];
  }

  // Fallback: Perform clever word replacements
  let result = text;
  for (const [pattern, replacement] of SUDANESE_WORD_REPLACEMENTS) {
    result = result.replace(pattern, replacement);
  }

  return result;
}

/**
 * Checks the dialect and translates if necessary
 */
export function getDialectText(text: string, dialect?: string): string {
  if (dialect === 'sudanese') {
    return translateToSudanese(text);
  }
  return text;
}

export function getSudaneseHighlightWord(highlightWord?: string): string {
  if (!highlightWord) return '';
  if (highlightWord.includes('بِلُطْفٍ')) return 'بِظَرَافَة';
  if (highlightWord.includes('مَبْعُثَرَةً')) return 'مُجَوَّطَة';
  if (highlightWord.includes('تَنْظِيفٍ')) return 'نَظَافَة';
  if (highlightWord.includes('الخَلَاءِ')) return 'الحَمَّام';
  return highlightWord;
}
